import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Readable, Writable } from 'node:stream';
import { createWorkspace } from '../src/workspace.js';
import { createScheduler } from '../src/scheduler.js';
import { createServer } from '../src/server.js';
import { createProviderRegistry } from '../src/provider.js';
import { createPreviewServer, extractHTML } from '../src/preview.js';

test('HTTP API keeps files scoped to their session and accepts temporary skill calls', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'employee-http-'));
  const app = createWorkspace(join(dir, 'app.db'));
  const scheduler = createScheduler(app, async () => ({ text: '完成' }));
  const registry = createProviderRegistry({ kimiKey: '', deepseekKey: '', fetchImpl: async () => ({ ok: true, json: async () => ({ choices: [{ message: { content: '<html><body><button id="b">试试</button><script>document.querySelector("#b").onclick=()=>alert("ok")</script></body></html>' } }] }) }) });
  const server = createServer(app, scheduler, { providerRegistry: registry, publicOrigin: 'https://47.83.139.234', previewPublicUrl: 'https://www.zenanxing.cloud/ai-team-preview' });
  t.after(() => { app.close(); rmSync(dir, { recursive: true, force: true }); });
  const request = async (path, method = 'GET', body, headers = {}) => {
    const req = Readable.from(body ? [JSON.stringify(body)] : []);
    req.url = path;
    req.method = method;
    req.headers = headers;
    const chunks = [];
    let status = 200;
    let responseHeaders = {};
    const res = new Writable({ write(chunk, encoding, done) { chunks.push(chunk); done(); } });
    res.writeHead = (code, values) => { status = code; responseHeaders = values; res.headersSent = true; };
    const done = new Promise(resolve => res.on('finish', () => resolve({ status, headers: responseHeaders, bytes: Buffer.concat(chunks) })));
    server.emit('request', req, res);
    const response = await done;
    return { ...response, body: response.headers['Content-Type']?.includes('json') ? JSON.parse(response.bytes.toString()) : null };
  };
  const page = await request('/');
  assert.equal(page.status, 200);
  assert.match(page.bytes.toString(), /AI 员工工作空间/);
  assert.equal((await request('/missing-file')).status, 404);
  assert.equal((await request('/api/bootstrap')).body.previewBaseUrl, 'https://www.zenanxing.cloud/ai-team-preview');
  assert.equal((await request('/api/sessions', 'POST', {}, { origin: 'https://evil.example', host: '47.83.139.234' })).status, 403);
  assert.equal((await request('/api/sessions', 'POST', {}, { origin: 'https://47.83.139.234', host: '47.83.139.234' })).status, 201);
  const one = (await request('/api/sessions', 'POST', {})).body;
  const two = (await request('/api/sessions', 'POST', {})).body;
  const file = (await request(`/api/sessions/${one.id}/files`, 'POST', { name: 'private.txt', mime: 'text/plain', base64: Buffer.from('private').toString('base64') })).body;
  assert.equal((await request(`/api/sessions/${two.id}/files/${file.id}`)).status, 404);
  assert.equal((await request(`/api/sessions/${one.id}/files/${file.id}`)).status, 200);
  assert.equal((await request('/api/skills/web-build', 'PATCH', { installed: true, enabled: true })).status, 200);
  assert.equal((await request(`/api/sessions/${one.id}/messages`, 'POST', { content: '先试试' })).status, 409);
  const configured = await request('/api/provider', 'POST', { provider: 'deepseek', model: 'deepseek-flash', key: 'local-test-secret' });
  assert.equal(configured.status, 200);
  assert.equal(configured.body.name, 'DeepSeek');
  assert.ok(!JSON.stringify(configured.body).includes('local-test-secret'));
  const skillCheck = await request('/api/skills/web-build/test', 'POST', {});
  assert.equal(skillCheck.status, 200);
  assert.equal(skillCheck.body.ok, true);
  const sent = await request(`/api/sessions/${one.id}/messages`, 'POST', { content: '/网页开发 做一个记账页面' });
  assert.equal(sent.status, 201);
  assert.deepEqual(sent.body.skillIds, ['web-build']);
  await scheduler.waitForIdle();
  const steeringRun = app.createRun(one.id, '制作新页面', [], []);
  assert.equal((await request(`/api/runs/${steeringRun.id}`)).status, 404);
  assert.equal((await request(`/api/sessions/${two.id}/runs/${steeringRun.id}`)).status, 404);
  assert.equal((await request(`/api/sessions/${one.id}/runs/${steeringRun.id}`)).status, 200);
  assert.equal((await request(`/api/sessions/${two.id}/runs/${steeringRun.id}/cancel`, 'POST', {})).status, 404);
  assert.equal((await request(`/api/sessions/${two.id}/runs/${steeringRun.id}/retry`, 'POST', {})).status, 404);
  assert.equal((await request(`/api/sessions/${two.id}/runs/${steeringRun.id}/steer`, 'POST', { content: '使用蓝色' })).status, 404);
  assert.equal((await request(`/api/sessions/${one.id}/runs/${steeringRun.id}/steer`, 'POST', { content: '使用蓝色' })).body.metadata.steeringRunId, steeringRun.id);
  assert.equal((await request(`/api/sessions/${two.id}/runs/${sent.body.id}/review`, 'POST', { decision: 'accept' })).status, 404);
  const acceptedDelivery = await request(`/api/sessions/${one.id}/runs/${sent.body.id}/review`, 'POST', { decision: 'accept' });
  assert.equal(acceptedDelivery.status, 200);
  assert.equal(acceptedDelivery.body.review.status, 'accepted');
  assert.equal((await request(`/api/sessions/${one.id}/runs/${sent.body.id}/review`, 'POST', { decision: 'accept' })).status, 400);
  const htmlFile = app.addFile(one.id, 'index.html', 'text/html; charset=utf-8', Buffer.from('说明\n```html\n<!doctype html><html><body><button>应用</button></body></html>\n```'));
  const beforeOpen = app.getSession(one.id).runs.length;
  const opened = await request(`/api/sessions/${one.id}/messages`, 'POST', { content: '帮我打开应用' });
  assert.equal(opened.status, 200);
  assert.equal(opened.body.opened, htmlFile.id);
  assert.equal(app.getSession(one.id).runs.length, beforeOpen);
  assert.equal(app.getSession(one.id).messages.at(-1).metadata.fileId, htmlFile.id);
  assert.match(extractHTML('说明\n<!doctype html><html>ok</html>\n后记'), /^<!doctype html>/);
  const preview = createPreviewServer(app);
  const previewRequest = async path => {
    const req = Readable.from([]); req.url = path; req.method = 'GET';
    const chunks = []; let status;
    const res = new Writable({ write(chunk, encoding, done) { chunks.push(chunk); done(); } });
    res.writeHead = code => { status = code; };
    const finished = new Promise(resolve => res.on('finish', () => resolve({ status, body: Buffer.concat(chunks).toString() })));
    preview.emit('request', req, res);
    return finished;
  };
  assert.match((await previewRequest(`/app/${one.id}/${htmlFile.id}`)).body, /<button>应用<\/button>/);
  assert.equal((await previewRequest(`/app/${two.id}/${htmlFile.id}`)).status, 404);
  assert.equal(app.getSession(one.id).agents[0].skillIds.length, 0);
  const teammates = app.listProfiles().map(profile => app.addAgent(one.id, { profileId: profile.id }));
  const planned = app.createRun(one.id, '开发一个 Web 应用', [], teammates.map(agent => agent.id));
  const suggestion = planned.suggestions[0];
  assert.equal((await request(`/api/sessions/${two.id}/runs/${planned.id}/suggestions/${suggestion.id}`, 'POST', { decision: 'approve' })).status, 404);
  const review = await request(`/api/sessions/${one.id}/runs/${planned.id}/suggestions/${suggestion.id}`, 'POST', { decision: 'approve', title: '整理交付小结' });
  assert.equal(review.status, 200);
  assert.equal(review.body.suggestion.status, 'approved');
  assert.equal(review.body.run.tasks.some(task => task.title === '整理交付小结'), true);
  await scheduler.waitForIdle();
});
